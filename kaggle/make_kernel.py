"""Prepare (but do not launch) a private Kaggle training job on a T4 x2 machine.

Two folders are written under kaggle/build/:
  code/            src/ + requirements.txt as a private Kaggle *dataset*
                   (upload: kaggle datasets create -p kaggle/build/code
                    or, later, kaggle datasets version -p kaggle/build/code -m "update")
  <slug>/          a private *script kernel* that trains the requested folds,
                   two at a time (one per GPU), predicts their validation folds
                   and keeps weights + out-of-fold maps as the kernel output
                   (launch: kaggle kernels push -p kaggle/build/<slug>;
                    results: kaggle kernels output <user>/<slug> -p <dir>)

Example:
    .venv\\Scripts\\python.exe kaggle\\make_kernel.py --user <kaggle-user> --slug fil-effv2s-soft \\
        --prefix effv2s_soft --folds 0 1 2 3 4 \\
        --train-args "--encoder tu-tf_efficientnetv2_s --epochs 40 --bs 8 --crop 768"
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "kaggle" / "build"
COMPETITION = "filament-segmentation-2026"

# Packages missing from (or at a different version in) the Kaggle image; torch comes from the image.
PIP = "segmentation-models-pytorch==0.6.0 timm==1.0.31 albumentations==2.0.8 pycocotools"

RUNNER = r'''"""Kaggle training job (generated by kaggle/make_kernel.py)."""
import glob, os, shutil, subprocess, sys, threading
from pathlib import Path

CONFIG = __CONFIG__

subprocess.run(f"{sys.executable} -m pip install -q {CONFIG['pip']}", shell=True, check=True)

# Code: copied out of the read-only dataset so models/ and preds/ can be written next to it.
code = [p for p in glob.glob("/kaggle/input/**/src/train.py", recursive=True)]
assert len(code) == 1, code
PROJ = Path("/kaggle/working/proj")
shutil.copytree(Path(code[0]).parents[1], PROJ, dirs_exist_ok=True)

# Data: the competition folder is read-only, so caches go to /tmp (not kept as output).
data = glob.glob("/kaggle/input/**/MAGFiLO_1.0_Kaggle_2026", recursive=True)
assert len(data) == 1, data
env = dict(os.environ, FIL_DATA_ROOT=str(Path(data[0]).parent), FIL_CACHE_DIR="/tmp/cache",
           PYTHONWARNINGS="ignore")

def run(cmd, gpu=None):
    e = dict(env) if gpu is None else dict(env, CUDA_VISIBLE_DEVICES=str(gpu))
    print("$", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True, cwd=PROJ, env=e)

subprocess.run("nvidia-smi", shell=True)
for size in CONFIG["sizes"]:
    run(f"{sys.executable} src/prepare.py --size {size}")
for cmd in CONFIG["extra_prep"]:
    run(cmd.replace("python ", f"{sys.executable} ", 1))

def worker(gpu, folds):
    for k in folds:
        name = f"{CONFIG['prefix']}_f{k}"
        os.makedirs(PROJ / "models" / name, exist_ok=True)
        run(f"{sys.executable} src/train.py --name {name} --fold {k} {CONFIG['train_args']} "
            f"> models/{name}/train.out 2>&1", gpu)
        run(f"{sys.executable} src/infer.py --runs {name} --split val --fold {k} --out {name}", gpu)
        (PROJ / "models" / name / "last.pt").unlink(missing_ok=True)  # keep only the selected checkpoint

n_gpu = max(1, int(subprocess.run("nvidia-smi -L | wc -l", shell=True, capture_output=True, text=True).stdout))
folds = CONFIG["folds"]
threads = [threading.Thread(target=worker, args=(g, folds[g::n_gpu])) for g in range(n_gpu)]
for t in threads: t.start()
for t in threads: t.join()
for log in sorted(PROJ.glob("models/*/train.out")):
    print(log.parent.name, open(log).read().strip().splitlines()[-1][:200])
'''


def build_code_dataset(user: str) -> Path:
    out = BUILD / "code"
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(ROOT / "src", out / "src", ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy(ROOT / "requirements.txt", out / "requirements.txt")
    meta = dict(title="filament-code", id=f"{user}/filament-code", licenses=[dict(name="other")])
    (out / "dataset-metadata.json").write_text(json.dumps(meta, indent=2))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True, help="Kaggle user name (kept out of the repository)")
    ap.add_argument("--slug", required=True)
    ap.add_argument("--prefix", required=True, help="run names become <prefix>_f<k>")
    ap.add_argument("--folds", type=int, nargs="+", default=[0, 1, 2, 3, 4])
    ap.add_argument("--train-args", required=True)
    ap.add_argument("--sizes", type=int, nargs="+", default=[1024], help="caches to build")
    ap.add_argument("--extra-prep", nargs="*", default=[], help="extra commands run in the project folder")
    args = ap.parse_args()

    code = build_code_dataset(args.user)
    kdir = BUILD / args.slug
    kdir.mkdir(parents=True, exist_ok=True)
    config = dict(prefix=args.prefix, folds=args.folds, train_args=args.train_args, sizes=args.sizes,
                  extra_prep=args.extra_prep, pip=PIP)
    (kdir / "run.py").write_text(RUNNER.replace("__CONFIG__", repr(config)), encoding="utf-8")
    meta = dict(id=f"{args.user}/{args.slug}", title=args.slug, code_file="run.py", language="python",
                kernel_type="script", is_private=True, enable_gpu=True, enable_tpu=False, enable_internet=True,
                dataset_sources=[f"{args.user}/filament-code"], competition_sources=[COMPETITION],
                kernel_sources=[], model_sources=[], machine_shape="NvidiaTeslaT4")
    (kdir / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print("code dataset:", code)
    print("kernel:", kdir)
    print("nothing was uploaded; see the module docstring for the upload commands")


if __name__ == "__main__":
    main()
